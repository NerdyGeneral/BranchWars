// Live source embeds -- these are the formulas themselves, not a description of them.
for (const fn of ['doctrineProfile', 'executionCapacity', 'hireCost', 'projectCost', 'projectCycles', 'depositPull', 'advanceProjects', 'baseScore', 'capitalRatio']) {
  sections['SRC_' + fn] = '```js\n' + sourceOf(fn) + '\n```';
}

// -------------------------------------------------------------------- render

let out = fs.readFileSync(TEMPLATE, 'utf8').replace(/\r\n/g, '\n');
const used = new Set();
out = out.replace(/<!--\{\{([A-Za-z_]+)\}\}-->/g, (m, token) => {
  if (!(token in sections)) throw new Error('Template asks for unknown section: ' + token);
  used.add(token);
  return sections[token];
});
const unused = Object.keys(sections).filter((k) => !used.has(k));
if (unused.length) throw new Error('Generated sections never placed in the template: ' + unused.join(', '));




if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== out.replace(/\r\n/g, '\n')) {
    console.error('docs/game-reference.md is out of date with the engine.');
    console.error('Run: node tools/build_reference.js');
    process.exit(1);
  }
  console.log('docs/game-reference.md is current.');
} else {
  fs.writeFileSync(OUT, out);
  const counts = {
    markets: Object.keys(E.TERRITORIES).length,
    initiatives: liveProjects.length,
    'pilot initiatives': pilotProjects.length,
    'capability tiers': Object.values(E.CAPABILITY_TIERS).reduce((n, t) => n + t.length, 0),
    'competitive actions': Object.keys(E.COMPETITIVE_ACTIONS).length - 1,
    events: E.EVENTS.length,
    mandates: Object.keys(E.MANDATES).length,
    milestones: Object.keys(E.MILESTONES).length,
  };
  console.log('Wrote docs/game-reference.md —', Object.entries(counts).map(([k, v]) => v + ' ' + k).join(', '));
}
