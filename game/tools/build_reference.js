'use strict';
/*
 * Builds docs/game-reference.md from the live engine.
 *
 * Every number, name and description in the generated sections is read out of
 * BRANCH_WARS.html at build time, so the reference cannot drift from the game.
 * Prose lives in tools/reference-template.md and is the only part written by hand.
 *
 *   node tools/build_reference.js           rebuild docs/game-reference.md
 *   node tools/build_reference.js --check   fail if the committed file is stale
 *
 * The check runs as part of the test suite, so changing a cost or adding a
 * project without rebuilding the reference is a test failure rather than
 * something to remember.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const GAME = path.join(ROOT, 'BRANCH_WARS.html');
const TEMPLATE = path.join(__dirname, 'reference-template.md');
const OUT = path.join(ROOT, 'docs', 'game-reference.md');

// Normalize before parsing/formatting: sourceOf inserts LF line breaks, so
// normalizing only the final comparison cannot undo mixed-EOL blank lines.
const html = fs.readFileSync(GAME, 'utf8').replace(/\r\n/g, '\n');
const engineSource = html.match(/<script id="engine">([\s\S]*?)<\/script>/)[1];
const context = { console, Math, Date, globalThis: null };
context.globalThis = context;
vm.runInNewContext(engineSource, context, { filename: 'embedded-engine.js' });
const E = context.BWEngine;

// ---------------------------------------------------------------- formatting

const money = (n) => {
  if (!Number.isFinite(n)) return String(n);
  if (n === 0) return '$0';
  if (Math.abs(n) >= 1e6) return '$' + (n / 1e6).toFixed(2).replace(/\.00$/, '') + 'M';
  if (Math.abs(n) >= 1000) return '$' + Math.round(n / 1000) + 'K';
  return '$' + n;
};
const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim();
const table = (headers, rows) => {
  if (!rows.length) return '_none_';
  return [
    '| ' + headers.join(' | ') + ' |',
    '|' + headers.map(() => '---').join('|') + '|',
    ...rows.map((r) => '| ' + r.map(esc).join(' | ') + ' |'),
  ].join('\n');
};

/* Pulls a top-level function out of the engine source by brace matching, so the
   reference shows the logic that is actually running rather than a paraphrase. */
function sourceOf(name) {
  const needle = 'function ' + name + '(';
  const start = engineSource.indexOf(needle);
  if (start === -1) return '// not found: ' + name;
  let depth = 0;
  let i = engineSource.indexOf('{', start);
  const open = i;
  for (; i < engineSource.length; i++) {
    if (engineSource[i] === '{') depth++;
    else if (engineSource[i] === '}') {
      depth--;
      if (depth === 0) break;
    }
  }
  const body = engineSource.slice(start, i + 1);
  // The engine is minified onto few lines; break after statements so it reads.
  return body.replace(/;(?![^(]*\))/g, ';\n').replace(/\n{2,}/g, '\n').trim();
}

